// StrictMode refuses WebSocket connections without a valid token (default ON).
// Escape hatch: CRIMSON_STRICT_AUTH=0|false|off|no
func StrictMode() bool {
	v := strings.TrimSpace(strings.ToLower(os.Getenv("CRIMSON_STRICT_AUTH")))
	if v == "" {
		return true
	}
	return !(v == "0" || v == "false" || v == "off" || v == "no")
}

var (
	mu      sync.RWMutex
	current string
)

// GenerateAndSaveToken regenerates the local WS auth token on every start
// (same behaviour as the Rust sidecar) and writes auth.token under the data dir.
func GenerateAndSaveToken() string {
	token := uuid.NewString()
	path := filepath.Join(storage.DataDir(), "auth.token")
	if err := os.WriteFile(path, []byte(token), 0o600); err != nil {
		log.Printf("[auth] failed to write auth.token: %v", err)
	} else {
		log.Printf("[auth] token saved to %s", path)
	}
	mu.Lock()
	current = token
	mu.Unlock()
	publishTokenToStreamDockPlugins(token)
	return token
}

func CurrentToken() string {
	mu.RLock()
	if current != "" {
		t := current
		mu.RUnlock()
		return t
	}
	mu.RUnlock()
	path := filepath.Join(storage.DataDir(), "auth.token")
	b, err := os.ReadFile(path)
	if err != nil {
		return ""
	}
	t := strings.TrimSpace(string(b))
	mu.Lock()
	current = t
	mu.Unlock()
	return t
}

// Verify compares candidate to the current token in constant time.
func Verify(candidate string) bool {
	expected := CurrentToken()
	if expected == "" || candidate == "" {
		return false
	}
	if len(candidate) != len(expected) {
		return false
	}
	return subtle.ConstantTimeCompare([]byte(candidate), []byte(expected)) == 1
}

func publishTokenToStreamDockPlugins(token string) {
	appdata := os.Getenv("APPDATA")
	if appdata == "" {
		return
	}
	base := filepath.Join(appdata, "HotSpot", "StreamDock", "plugins")
	safe := strings.ReplaceAll(strings.ReplaceAll(token, `\`, `\\`), `'`, `\'`)
	js := "/* generated by crimson-server — do not edit */\nwindow.__CRIMSON_AUTH_TOKEN__ = '" + safe + "';\n"
	pluginIDs := []string{
		"com.laoy.streamdock.spotify.sdPlugin",
		"com.laoy.streamdock.crimson.sdPlugin",
		"com.laoy.streamdock.discord.sdPlugin",
		"com.laoy.streamdock.applemusic.sdPlugin",
	}
	for _, id := range pluginIDs {
		for _, rel := range []string{"plugin/crimson_auth_token.js", "crimson_auth_token.js"} {
			path := filepath.Join(base, id, rel)
			if parent := filepath.Dir(path); dirExists(parent) {
				_ = os.WriteFile(path, []byte(js), 0o644)
			}
		}
	}
}

func dirExists(p string) bool {
	st, err := os.Stat(p)
	return err == nil && st.IsDir()
}

// --- Supabase session (shared file with Tauri UI) ---

const sessionFile = "supabase_session.json"

type Session struct {
	AccessToken  string `json:"access_token"`
	RefreshToken string `json:"refresh_token,omitempty"`
	ExpiresAt    *int64 `json:"expires_at,omitempty"`
}

var (
	sessionMu sync.RWMutex
	session   *Session
	premium   bool
)

func sessionPath() string {
	return filepath.Join(storage.DataDir(), sessionFile)
}

// LoadSessionFromDisk restores tokens so StreamDock works without the UI.
func LoadSessionFromDisk() {
	raw, err := os.ReadFile(sessionPath())
	if err != nil {
		return
	}
	var s Session
	if err := json.Unmarshal(raw, &s); err != nil || s.AccessToken == "" {
		return
	}
	sessionMu.Lock()
	session = &s
	sessionMu.Unlock()
}

func SetSession(access string, refresh *string) {
	sessionMu.Lock()
	defer sessionMu.Unlock()
	if session == nil {
		session = &Session{}
	}
	session.AccessToken = access
	if refresh != nil && *refresh != "" {
		session.RefreshToken = *refresh
	}
	saveSessionLocked()
}

func ClearSession() {
	sessionMu.Lock()
	session = nil
	premium = false
	sessionMu.Unlock()
	_ = os.Remove(sessionPath())
}

func ExportedTokens() (access, refresh string, ok bool) {
	sessionMu.RLock()
	defer sessionMu.RUnlock()
	if session == nil || session.AccessToken == "" {
		return "", "", false
	}
	return session.AccessToken, session.RefreshToken, true
}

func IsPremium() bool {
	sessionMu.RLock()
	defer sessionMu.RUnlock()
	return premium
}

func SetPremium(v bool) {
	sessionMu.Lock()
	premium = v
	sessionMu.Unlock()
}

func AccessToken() string {
	sessionMu.RLock()
	defer sessionMu.RUnlock()
	if session == nil {
		return ""
	}
	return session.AccessToken
}

func saveSessionLocked() {
	if session == nil {
		return
	}
	raw, _ := json.MarshalIndent(session, "", "  ")
	_ = os.WriteFile(sessionPath(), raw, 0o600)
}
